static int oled_cmd(const uint8_t *cmds, uint8_t n) {
	uint8_t buf[17];
	if (n == 0 || n > 16) {
		return -1;
	}
	buf[0] = 0x00;
	for (uint8_t i = 0; i < n; i++) {
		buf[i + 1] = cmds[i];
	}
	return i2c_write_raw(OLED_ADDR, buf, (uint8_t)(n + 1));
}

static void oled_page(uint8_t page, const uint8_t pixels[OLED_WIDTH]) {
	uint8_t mode[2] = {0x20, 0x00};
	uint8_t cols[3] = {0x21, 0x00, 0x7F};
	uint8_t pages[3] = {0x22, page, page};
	uint8_t buf[OLED_WIDTH + 1];

	oled_cmd(mode, 2);
	oled_cmd(cols, 3);
	oled_cmd(pages, 3);

	buf[0] = 0x40;
	for (uint8_t col = 0; col < OLED_WIDTH; col++) {
		buf[col + 1] = pixels[col];
	}
	i2c_write_raw(OLED_ADDR, buf, OLED_WIDTH + 1);
}

void oled_init(void) {
	static const uint8_t setup[] = {
		0xAE,
		0xD5, 0x80,
		0xA8, 0x3F,
		0xD3, 0x00,
		0x40,
		0x8D, 0x14,
		0x20, 0x00,
		0xA1,
		0xC8,
		0xDA, 0x12,
		0x81, 0x7F,
		0xD9, 0xF1,
		0xDB, 0x40,
		0xA4,
		0xA6,
		0xAF,
	};
	uint8_t blank[OLED_WIDTH];
	uint8_t i = 0;

	while (i < sizeof setup) {
		uint8_t n = 1;
		/* Commands 0xD5, 0xA8, 0xD3, 0x8D, 0x20, 0xDA, 0x81, 0xD9, 0xDB take one argument. */
		switch (setup[i]) {
		case 0xD5:
		case 0xA8:
		case 0xD3:
		case 0x8D:
		case 0x20:
		case 0xDA:
		case 0x81:
		case 0xD9:
		case 0xDB:
			n = 2;
			break;
		default:
			break;
		}
		oled_cmd(&setup[i], n);
		i = (uint8_t)(i + n);
	}

	for (uint8_t col = 0; col < OLED_WIDTH; col++) {
		blank[col] = 0;
	}
	for (uint8_t page = 0; page < OLED_PAGES; page++) {
		oled_page(page, blank);
	}
}

void oled_show_line(const char *text) {
	uint8_t line[OLED_WIDTH];
	uint8_t col = 0;

	for (uint8_t i = 0; i < OLED_WIDTH; i++) {
		line[i] = 0;
	}

	if (text != 0) {
		for (uint8_t i = 0; text[i] != '\0' && col + GLYPH_W <= OLED_WIDTH; i++) {
			unsigned char c = (unsigned char)text[i];
			const uint8_t *glyph = 0;
			if (c >= 0x20 && c <= 0x7A) {
				glyph = &font[(c - 0x20) * GLYPH_W];
			}
			for (uint8_t g = 0; g < GLYPH_W; g++) {
				line[col++] = glyph ? glyph[g] : 0;
			}
			if (col < OLED_WIDTH) {
				line[col++] = 0;
			}
		}
	}

	oled_page(0, line);
}
